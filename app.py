import streamlit as st
import pandas as pd
import joblib

# Load the trained Constrained Random Forest model and encodings
@st.cache_resource
def load_assets():
    model = joblib.load('dubai_rf_model.pkl')
    encodings = joblib.load('area_encoding.pkl')
    return model, encodings

model, area_encodings = load_assets()

st.title("🏙️ Dubai Real Estate Valuation Model")
st.write("Predict residential property prices based on historical Dubai Land Department data.")

st.sidebar.header("Property Details")
selected_area = st.sidebar.selectbox("Neighborhood", options=sorted(list(area_encodings.keys())))
property_type = st.sidebar.radio("Property Type", ["Unit", "Villa"])
rooms = st.sidebar.slider("Number of Rooms (0 for Studio)", min_value=0, max_value=7, value=1)
area_sqft = st.sidebar.number_input("Property Size (SqFt)", min_value=300, max_value=15000, value=800, step=50)
has_parking = st.sidebar.checkbox("Has Parking?", value=True)

if st.sidebar.button("Predict Market Price"):
    # Format room label to match the raw DLD strings
    room_label = "Studio" if rooms == 0 else f"{rooms} B/R"
    
    # 1. Create base inputs
    input_data = {
        'has_parking': 1 if has_parking else 0,
        'area_sqft': area_sqft,
        'transaction_year': 2026, 
        'transaction_month': 11,
        'area_encoded': area_encodings.get(selected_area, 0),
        'property_type_Villa': 1 if property_type == "Villa" else 0,
        f'rooms_{room_label}': 1
    }
    
    input_df = pd.DataFrame([input_data])
    
    # 2. Bulletproof feature alignment: force columns to match the trained model exactly
    # Any missing columns (like other room types) are automatically filled with 0
    input_df = input_df.reindex(columns=model.feature_names_in_, fill_value=0)
    
    # 3. Generate the prediction
    prediction = model.predict(input_df)[0]
    
    st.subheader(f"Estimated Valuation in {selected_area}")
    st.metric(label="Predicted Price (AED)", value=f"AED {prediction:,.0f}")
    st.info("Valuation generated by a Constrained Random Forest model trained on official DLD data.")